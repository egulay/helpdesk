CREATE TABLE issue_requester
(
    id        INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    email     VARCHAR(320) NOT NULL,
    is_active BOOLEAN      NOT NULL DEFAULT TRUE,
    created   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_issue_requester_email UNIQUE (email)
);

CREATE INDEX idx_issue_requester_created ON issue_requester (created);
CREATE INDEX idx_issue_requester_active_created ON issue_requester (is_active, created);

CREATE TABLE issue_request
(
    id           INTEGER   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id INTEGER   NOT NULL,
    request_body TEXT      NOT NULL,
    is_solved    BOOLEAN   NOT NULL DEFAULT FALSE,
    created      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    solved       TIMESTAMP NULL,
    CONSTRAINT fk_issue_request_requester
        FOREIGN KEY (requester_id) REFERENCES issue_requester (id)
            ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX idx_issue_request_requester_created ON issue_request (requester_id, created);
CREATE INDEX idx_issue_request_solved_created ON issue_request (is_solved, created);
CREATE INDEX idx_issue_request_solved_at ON issue_request (solved);

CREATE TABLE issue_response
(
    id            INTEGER   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id    INTEGER   NOT NULL,
    requester_id  INTEGER   NOT NULL,
    response_body TEXT      NOT NULL,
    created       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_issue_response_requester
        FOREIGN KEY (requester_id) REFERENCES issue_requester (id)
            ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_issue_response_request
        FOREIGN KEY (request_id) REFERENCES issue_request (id)
            ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX idx_issue_response_request_created ON issue_response (request_id, created);
CREATE INDEX idx_issue_response_requester_created ON issue_response (requester_id, created);
